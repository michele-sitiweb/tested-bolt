import { createContext, useContext, useEffect, useState, type ReactNode } from 'react';

export type Lang = 'it' | 'de' | 'en' | 'fr' | 'es';

export const languages: { code: Lang; label: string; flag: string }[] = [
  { code: 'it', label: 'Italiano', flag: '🇮🇹' },
  { code: 'de', label: 'Deutsch', flag: '🇩🇪' },
  { code: 'en', label: 'English', flag: '🇬🇧' },
  { code: 'fr', label: 'Français', flag: '🇫🇷' },
  { code: 'es', label: 'Español', flag: '🇪🇸' },
];

type I18nContextType = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
};

const I18nContext = createContext<I18nContextType>({
  lang: 'it',
  setLang: () => {},
  t: (key: string) => key,
});

export function useI18n() {
  return useContext(I18nContext);
}

function getInitialLang(): Lang {
  const stored = localStorage.getItem('tb_lang') as Lang | null;
  if (stored && ['it', 'de', 'en', 'fr', 'es'].includes(stored)) return stored;
  return 'it';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(getInitialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem('tb_lang', l);
  };

  const t = (key: string): string => {
    const dict = translations[lang] || translations.it;
    return dict[key] ?? translations.it[key] ?? key;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

